const path = require('path');
const { chromium } = require(path.join(process.env.NPM_GLOBAL || 'D:/node-dev/npm-global', 'node_modules/playwright-core'));
const EXE = path.join(process.env.USERPROFILE, 'AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe');
const FILE = 'file:///' + path.resolve(__dirname, 'mock_touch_layout.html').replace(/\\/g, '/');
(async () => {
  const b = await chromium.launch({ executablePath: EXE });
  const p = await (await b.newContext({ viewport: { width: 1200, height: 760 } })).newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(FILE, { waitUntil: 'load' });
  await p.waitForTimeout(500);
  await p.screenshot({ path: 'shots/mock_b_new.png' });
  await p.click('#tOld');
  await p.waitForTimeout(300);
  await p.screenshot({ path: 'shots/mock_a_old.png' });
  await p.click('#tNew'); await p.click('#tReach');
  await p.waitForTimeout(400);
  await p.screenshot({ path: 'shots/mock_c_reach.png' });
  console.log('errs:', errs.length ? errs[0] : 'none');
  await b.close();
})();
