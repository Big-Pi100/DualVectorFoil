#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Room01 关卡蓝图构建器（100 × 40 格 = 4800 × 1920 px）。

为什么要有这个脚本：
    上一版 34×15 是手写的 ASCII，一屏看得完，也能在聊天里讨论。
    这一版是 100×40 = 4000 个格子，手写必然错列（每行差一格，整张图就歪）。
    所以把"设计"放在下面的矩形列表里，ASCII 仍然由它渲染出来当**唯一产物** ——
    蓝图还是 diffable 的文本，只是不再手打。

用法：
    python build_room01_level.py          # 写 ../rooms/blueprints/room_01.txt
    python build_room01_level.py --show   # 只打印，不写文件

坐标：c0..c99 从左到右，r0..r39 从上到下。

**跳跃标定（生成器按这个验算，设计时必须守）**：
    单跳 204px = 4.25 格 → 一次最多升 **4 行**
    站在 r36 的楼板上，能跳到的最低平台是 r33（站 r32，升 4 行 = 192px）
    横向最多 **4 格**

于是所有纵向链条都按 r36 → r33 → r29 → r25 → r21 → r17 → r13 排，
每级正好 4 行。这个锚点错了，整条路就断了 —— 而生成器只会说"门不可达"，
不会告诉你断在哪一级。
"""

import os
import sys

W, H = 100, 40

g = [['#'] * W for _ in range(H)]


def carve(x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            assert 0 <= x < W and 0 <= y < H, (x, y)
            g[y][x] = '.'


def solid(x0, y0, x1, y1):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            g[y][x] = '#'


def plat(x0, x1, y):
    for x in range(x0, x1 + 1):
        assert g[y][x] == '.', 'c%d r%d 放平台时是实心（%s）' % (x, y, g[y][x])
        g[y][x] = '='


def put(x, y, ch):
    g[y][x] = ch


def ground_enemy(x):
    """把 'E' 放到该列**最低**的可站立格（和生成器的"掉到地面"一致）。"""
    for y in range(H - 2, 1, -1):
        if g[y][x] == '.' and g[y + 1][x] in ('#', '=') and g[y - 1][x] == '.':
            g[y][x] = 'E'
            return
    raise AssertionError('c%d 找不到可站立面' % x)


def air_enemy(x, y):
    assert g[y][x] == '.', 'c%d r%d 不是空的（%s）' % (x, y, g[y][x])
    g[y][x] = 'F'


# ================================================================ 1. 空腔
# A 入口高厅：c1..c28 一整块，19 行高。进门抬头能看见四层楼板。
carve(1, 18, 28, 36)
# B 主脊：c29..c48，8 行净高
carve(29, 29, 48, 36)
# C 竖井：从主脊天花板一路开到 r8
carve(42, 8, 48, 28)
# D 上层走廊：扳开关的地方
carve(46, 8, 62, 12)
# E 东厅：闸门左侧最后一块战场
carve(49, 26, 63, 36)
# F 出口走廊
carve(65, 26, 98, 36)
# G 小竖井 + H 瞭望台
carve(72, 14, 75, 25)
carve(70, 10, 80, 13)
# J 高空死路
carve(92, 24, 96, 28)

# ================================================================ 2. 实心重构
# 地面上的矮台（2 行高 = 96px）。原来是 3 行（192px），是单跳的极限 ——
# 走两步就要一次满跳，读起来像"每两米一堵墙"。DC 的地面起伏都是小台阶。
solid(4, 35, 10, 36)
solid(22, 35, 26, 36)
solid(31, 35, 36, 36)
# 闸门上方整面墙（只留 c64 的闸门段）
solid(64, 0, 64, 25)
# 上层走廊的地板必须**连续**到竖井口。
# 竖井 c42..c48 一路挖到 r28，如果 r13 只在 c49 之后才是实心，
# 玩家从最高一级平台往右走会直接掉回井底 —— 六跳白爬。
# 不是"难"，是"掉下去还不知道为什么"。所以把 c46..c48 的 r13 补实。
solid(46, 13, 48, 13)
# 下坠井 3 格宽。2 格宽实测会把玩家卡在井口：身体贴住对侧墙，
# y 在 631~658 之间抖，既不落下去也走不开。窄井不是难，是坏。
carve(58, 13, 60, 25)
# 瞭望台的地板，c72-c75 留口给小竖井
solid(70, 14, 71, 14)
solid(76, 14, 80, 14)

# ================================================================ 3. 平台
# 入口高厅：之字形四段，从 r33 一路上到 r21，顶端是死路（放 vista）
plat(16, 20, 33)
plat(22, 26, 29)
plat(16, 20, 25)
plat(22, 26, 21)
# 主脊：一块可跳可不跳的矮台
plat(38, 41, 33)
# 竖井 C：六级，左右交替，每级 4 行 —— 这是全关唯一的上升路线
plat(43, 46, 33)
plat(42, 45, 29)
plat(44, 47, 25)
plat(42, 45, 21)
plat(44, 47, 17)
plat(42, 45, 13)
# 上层走廊：一处落脚，免得一眼望到底
plat(52, 56, 10)
# 出口走廊的三块台（可选，上去只有视野）
plat(66, 70, 33)
plat(78, 82, 33)
plat(86, 89, 29)
# 小竖井 G：五级。竖井只有 4 格宽，所以每级都铺满 4 格 ——
# 判据 min_platform_span=4 是在防"浮板"：3 格宽的台子读不出路径。
plat(72, 75, 33)
plat(72, 75, 29)
plat(72, 75, 25)
plat(72, 75, 21)
plat(72, 75, 17)
# 通往高空死路 J
plat(89, 93, 33)
plat(90, 94, 29)

# ================================================================ 4. 机关
for r in range(26, 37):
    put(64, r, 'G')
# 开关格**就是站面那一格**：生成器把拉杆原点算成 (sw.y+1)*48，
# 也就是"站面的地面"。写成 r11 会让拉杆浮在地面上方 48px 处，
# 玩家站上去触发不到 —— 实测 `_interactable` 一直是 null。
put(56, 12, 'S')

# ================================================================ 5. 门与出生点
# 门格必须自己可站：门上方一格要是空的（`_standable` 要求头顶净空），
# 否则生成器会报"门不可达"。c0 / c99 本来是边界墙，要显式挖出 3 格门洞。
carve(0, 34, 0, 36)
carve(99, 34, 99, 36)
put(0, 36, 'L')
put(99, 36, 'R')
put(2, 35, 'P')

# ================================================================ 6. 敌人
for c in (6, 12, 18, 24, 33, 39, 45, 51, 57, 69, 77, 85, 95):
    ground_enemy(c)
for x, y in ((17, 24), (23, 20), (35, 32), (44, 16), (80, 32)):
    assert g[y][x] == '.', 'c%d r%d 不是空的' % (x, y)
    g[y][x] = 'E'
for c, r in ((11, 21), (27, 22), (54, 9), (67, 28), (88, 27)):
    air_enemy(c, r)


# ================================================================ 输出
rows = [''.join(row) for row in g]

HEADER = """! Room01 · 入口厅（第五次重做：整关尺度）
!
! 2026-11-27 第五次。白哥给了《死亡细胞》的**整关地图**截图，原话：
!   「这是细胞重生的单房间地图，能玩2-5分钟。你设计那个地图10秒都玩不了」
!
! 上一版（34×15 = 1.3 屏）结构是对的 —— 机关门、竖井、死路支线都在，
! 但**尺度差了一个数量级**：DC 的一关是"一条长主脊 + 挂在两边的房间 + 两三口竖井"，
! 玩家在里面要走、要打、要回头。1.3 屏装不下"走"这件事。
!
! 所以这一版不是改结构，是把同一个结构**铺开到整关的尺度**：
!   100 × 40 格 = 4800 × 1920 px（3.75 屏宽 × 2.7 屏高）
!
! ------ 空间骨架 ------
!
!   c1..c28   入口高厅  19 行高，两处台阶 + 之字形四段平台，顶端死路
!   c29..c48  主脊      8 行净高，一段地台
!   c42..c48  竖井      从主脊天花板开到 r8，六级平台，**全关唯一的上升路线**
!   c46..c62  上层走廊  扳开关的地方，c59 是下坠井
!   c49..c63  东厅      下坠落点，也是闸门前最后一块战场
!   c64       闸门      26..36 共 11 格满高，门上方是一整面墙
!   c65..c98  出口走廊  支线：小竖井 G 通瞭望台，c92 通高空死路 J
!
! ------ 动线 ------
!
!   进门 → 高厅往右 → 主脊 → 东厅被闸门拦住
!   → 回头进竖井（c42）→ 六跳上到 r12 上层走廊 → 往右扳开关（c56）
!   → 走到 c59 下坠井掉回东厅 → 闸门已开 → 穿过 → 出口走廊
!   → 路上可选：小竖井上瞭望台 / 高空死路 J
!
! 上去和下来不是同一条路 —— 这是 DC 每张图都在做的事。
!
! ------ 敌我编成 ------
!
!   13 只地面（铺在高厅 / 主脊 / 东厅 / 出口走廊四段）
!   5 只层上（之字台、竖井中段、出口台面）
!   5 只飞行
!   共 23 只。上一版 9 只铺在 1632px 里已经 12.9 秒清完，
!   4800px 里 9 只会变成"一路走过去没什么事"，密度必须跟着面积走。
!
! ------ 判据 ------
!
!   min_layers=6              6 个高度层
!   min_platform_span=4
!   min_ground_span=8         近战要展开
!   min_enemy_layers=3
!   min_flying_enemies=3
!   min_optional_platforms=3  至少 3 块平台"可以不去"
!   min_walk_px=3600          出生点到出口的**最短步行距离**下限
!
! 机关门三段论同上一版：门关着时开关够得着 / 门关着时右门到不了 / 门开着时到得了。
! `min_walk_px` 是这一版新加的判据，专门钉死"10 秒就能走完"这件事：
! 上一版净值 1.3 屏，这一版要求最短步行距离 ≥ 3.6 屏宽，否则直接拒绝生成。
room_id=room_01
scene=res://world/rooms/Room01.tscn
door_L=res://world/rooms/SafeHouse.tscn|SpawnFromRest|← 休息小屋
door_R=res://world/rooms/Room02.tscn|SpawnFromLeft|→ 画页二
min_layers=6
min_platform_span=4
min_ground_span=8
min_enemy_layers=3
min_flying_enemies=3
min_optional_platforms=3
min_walk_px=3600
! wireframe=1  线框稿。Terrain 里不许有任何贴图（生成器自检）。
! 切回贴图只要把它改成 0 再生成一次，地形一格不动。
wireframe=1
vista_at=24,20
---
"""

out = HEADER + '\n'.join(rows) + '\n'

if '--show' in sys.argv:
    print(out)
else:
    path = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                         '..', 'rooms', 'blueprints', 'room_01.txt'))
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(out)
    print('wrote %s (%d x %d)' % (path, W, H))
