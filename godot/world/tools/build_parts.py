#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""垂直模板构建器：让关卡从「一条横线」变成「一张网」。

为什么需要这一批零件：

    拼装器（gen_level.py）已经能跑，但模板池里六间房**全部只有左右门**。
    只有左右门意味着关卡图只能排成一条横线 —— 换模板、换种子、换顺序，
    产出的永远是"一条走廊 + 分段的盒子"。这不是拼装引擎的问题，
    是零件可选的门方向只有一个维度。

    所以这一批补两件事：
      1. 上下门 `U` / `D`，让拼装器能垂直缝合；
      2. 三个新形状：多层厅（横向主链的高版）、高塔（纯垂直竖井）、
         转角房（从左进、往下拐）。

    Dead Cells 的关卡是 2D 的：主脊横向走，竖井上下通，走廊上挂小房间。
    没有上下门，这个形状在数据结构层面就不存在。

**跳跃标定（设计时必须守，生成器会验算）**：
    单跳 204px = 4.25 格 → 一次最多升 4 行
    横向最多 4 格

用法：
    python build_parts.py           # 写 ../rooms/blueprints/part_*.txt
    python build_parts.py --show    # 只打印，不写文件
"""

import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "rooms" / "blueprints"


class Grid:
    def __init__(self, w: int, h: int):
        self.w, self.h = w, h
        self.g = [["#"] * w for _ in range(h)]

    def carve(self, x0, y0, x1, y1):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                assert 0 <= x < self.w and 0 <= y < self.h, (x, y)
                self.g[y][x] = "."

    def solid(self, x0, y0, x1, y1):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.g[y][x] = "#"

    def plat(self, x0, x1, y):
        for x in range(x0, x1 + 1):
            assert self.g[y][x] == ".", f"c{x} r{y} 放平台时是 {self.g[y][x]}"
            self.g[y][x] = "="

    def put(self, x, y, ch):
        assert 0 <= x < self.w and 0 <= y < self.h, (x, y)
        self.g[y][x] = ch

    def ground_enemy(self, x):
        for y in range(self.h - 2, 1, -1):
            if self.g[y][x] == "." and self.g[y + 1][x] in "#=" and self.g[y - 1][x] == ".":
                self.g[y][x] = "E"
                return
        raise AssertionError(f"c{x} 找不到可站立面")

    def air_enemy(self, x, y):
        assert self.g[y][x] == ".", f"c{x} r{y} 不是空的（{self.g[y][x]}）"
        self.g[y][x] = "F"

    def render(self):
        return "\n".join("".join(row) for row in self.g)

    # ------------------------------------------------------------------
    # 净空自检
    #
    # 2026-11-28 加的。缩尺寸时我把大厅顶层台从 r5 抬到 r2，
    # 画出来一切正常（平台是橙线，看得见），但**人站不直**：
    # 玩家高 64px = 1.33 格，脚踩在台面上时身体会伸进上面那一行的 16px。
    # 台面在 r2 时头顶只剩 r1 一行（48px）—— 平台存在，玩法不存在。
    #
    # 这条判据就是为了让"看不见的撞头"在生成阶段变红。
    # 规则：凡是"脚下是实心、自己这格是空的"位置，头顶那格不能是**墙**。
    #
    # 只查墙 `#`，不查平台 `=`：`=` 是单向平台，从下往上穿过去不挡人，
    # 头顶压着一块单向平台顶多是视觉上贴着头皮，不会把人卡住。
    # 而头顶是墙就一定会挤（玩家 64px 会伸进上面那行 16px），那是真站不直。
    PASSABLE = set(".*EFSG")

    def check_headroom(self, name: str) -> None:
        bad = []
        for y in range(1, self.h):
            for x in range(self.w):
                if self.g[y][x] != ".":
                    continue
                below = self.g[y + 1][x] if y + 1 < self.h else "#"
                if below not in "#=":
                    continue
                if self.g[y - 1][x] == "#":
                    bad.append((x, y))
        if bad:
            raise AssertionError(
                f"{name}: {len(bad)} 处站不直（头顶是墙）= {bad[:8]}"
            )


# ==========================================================================
# 多层厅 28 × 24
#
# 横向主链上的「高版房间」：进门是一片挑高空间，六层平台之字形往上。
# 和 room_01 的区别是它更"竖"、更窄，拼进关卡时让节奏抬一下。
#
# 2026-11-28 第八次：30 行 → 24 行。
# 原来 r1..r4 那四行是纯空气（最高的平台在 r5，头顶还要留 4 行才到天花板），
# 一间房白占 192px。整关有 4 件竖零件，每件都这样白留就是 1 屏。
# ==========================================================================

def hall():
    g = Grid(28, 24)
    g.carve(1, 1, 26, 20)          # 内腔 26 × 20
    g.solid(1, 21, 26, 23)         # 地板（站面 r20）

    # 五层之字形：每级 3 行（144px），相邻层横向重叠 ≥4 格，
    # 保证「从任意一侧走上去」都不断链。
    #
    # ❗ 顶层台只能到 r5，不能到 r2：玩家高 64px = 1.33 格，
    # 站上台面时身体占 r(y-1) 和 r(y-2) 的一部分。台面在 r2 时头顶只剩 r1 一行（48px），
    # 人根本站不直 —— 这是我第一次缩尺寸时踩的坑，平台画出来了但用不了。
    g.plat(2, 9, 17)
    g.plat(6, 13, 14)
    g.plat(10, 17, 11)
    g.plat(14, 21, 8)
    g.plat(10, 17, 5)

    # 地面障碍：一块 4 格高的台（192px < 单跳 204px），逼玩家跳一下而不是平推。
    g.solid(20, 25, 17, 20)

    g.put(0, 20, "L")
    g.put(27, 20, "R")

    # 敌人：地面两只分开站，上层两只按在平台上，空中一只。
    g.ground_enemy(4)
    g.ground_enemy(16)
    g.put(8, 16, "E")   # r17 平台
    g.put(16, 10, "E")  # r11 平台（c16 在 plat 的 10..17 里）
    g.air_enemy(12, 7)

    return g


# ==========================================================================
# 高塔 18 × 24
#
# 纯垂直。上门 U 在顶行、下门 D 在底行，中间五层错落楼板。
# 玩家从上面掉进来，一层层往下落，最后从底部的洞掉到下一间。
#
# 2026-11-28 第八次：42 行 → 24 行。原版有两个硬伤：
#   ① 上门在 r0，而第一块楼板在 r37 —— 进塔第一步是**自由落体 33 行**（1584px），
#      不是"一层层往下"，是把整座塔一次掉完；
#   ② 最底一块楼板在 r5，D 门在 r41 —— 最后还要再掉 36 行。
#      两段巨落把中间那 8 层次要化了：玩家记住的只有"掉、掉"。
# 现在楼板从 r4 起、每 4 行一层到 r20，进门先落 4 行，出塔前落 3 行。
# 「掉一层、横穿、再掉一层」这个节奏才立得住。
# ==========================================================================

def tower():
    g = Grid(18, 24)
    g.carve(1, 1, 16, 22)          # 竖井内腔 16 × 22

    # 每层是一整块楼板（单向平台），只留 2 格缺口。
    #
    # 为什么不是"左右交替的短平台"：第一版就是这么写的，结果 U 在 c8，
    # 而所有短平台都在 c1-c7 / c10-c15 —— 玩家从上门掉进来，脚下一路没东西接，
    # 直接穿过整座塔从下门出去了。塔变成了滑梯。
    #
    # 整层楼板 + 交错缺口之后，玩法是"走到缺口掉下一层"：
    # 每层都得横穿半座塔，不会站着不动就掉下去。
    gaps = {
        4: (12, 13),   # 进门第一块：缺口放远侧，人先稳稳落在 c8 上方
        8: (4, 5),
        12: (12, 13),
        16: (8, 9),
        20: (4, 5),
    }
    for y, (ga, gb) in gaps.items():
        if ga > 1:
            g.plat(1, ga - 1, y)
        if gb < 16:
            g.plat(gb + 1, 16, y)

    # 上门：顶行 c8；下门：底行 c8。
    # 底部 r22 挖开 3 格，人才能从 r22 掉进 r23 的洞里。
    g.put(8, 0, "U")
    g.carve(7, 22, 9, 22)
    g.put(8, 23, "D")

    # 三层各一只地面怪 + 两只蝙蝠：塔里没有横向逃逸空间，战斗是被迫的。
    g.put(3, 3, "E")
    g.put(14, 7, "E")
    g.put(14, 11, "E")
    g.air_enemy(12, 6)
    g.air_enemy(4, 14)

    return g


# ==========================================================================
# 转角房 24 × 20
#
# 从左门进，走到右侧的洞往下掉。用在「主链要拐到下一层」的位置。
# 内部四层平台是可选探索，不是必经 —— 支线不该是死路。
#
# 2026-11-28 第八次：28 行 → 20 行。原来最高的平台在 r10，头顶还有 9 行空腔。
# ==========================================================================

def corner():
    g = Grid(24, 20)
    g.carve(1, 1, 22, 16)
    g.solid(1, 17, 22, 19)         # 地板（站面 r16）

    # 下坠井：c11..c13 从地板一直挖到底行，底行 c12 是 D 门。
    g.carve(11, 17, 13, 19)
    g.put(12, 19, "D")

    g.put(0, 16, "L")

    # 四层可选平台（之字形），跳过洞时能看见上面的路。
    g.plat(3, 9, 13)
    g.plat(11, 17, 10)
    g.plat(3, 9, 7)
    g.plat(11, 17, 4)

    g.ground_enemy(4)
    g.ground_enemy(18)
    g.put(6, 12, "E")    # r13 平台
    g.air_enemy(15, 8)

    return g


# ==========================================================================
# 落地厅 24 × 18
#
# 纵向转回横向。玩家从上一间的下门掉进来（这里的天花板洞），落地后走到右门。
# 没有这一件，垂直段只能一路往下到终点 —— 关卡就成了一条"下去的楼梯"，
# 而不是 DC 那种"横向主干 + 竖向捷径 + 回到横向"的网。
#
# 2026-11-28 第八次：26 行 → 18 行（最高平台在 r3 之上还有 3 行，够用了）。
# ==========================================================================

def landing():
    g = Grid(24, 18)
    g.carve(1, 1, 22, 14)
    g.solid(1, 15, 22, 17)         # 地板（站面 r14）

    # 上门开在 c6，正对着一块挑台 —— 掉下来不会直接砸在地面中心，
    # 而是先落在 r10 的台上，再从台边走到地面。落点有停顿才有"落地感"。
    g.put(6, 0, "U")
    g.plat(3, 9, 10)

    # 两层可选平台，给右半段一点纵向空间。
    g.plat(13, 19, 7)
    g.plat(13, 19, 3)

    g.put(23, 14, "R")

    g.ground_enemy(3)
    g.ground_enemy(17)
    g.put(16, 6, "E")
    g.air_enemy(11, 5)

    return g


# ==========================================================================
# 梯台竖井 18 × 13（支线）
#
# 挂在主链某间的**地板洞**下面。玩家走过去的会掉进来，掉在顶层台上；
# 想深就按「下 + 跳」下穿一层，想走就原地跳回洞口出去。
#
# ----- 为什么不是"掉到底再爬回来" -----
# 我按这个思路画过两版，都爬不出来，第三版才想明白**物理上就不可能**：
#   单跳 204px（重力 1940，起跳 -890），而要走的路是
#   「洞口地板 3 格(144) + 身高 1.33 格(64) = 208px」，比一次跳还多 4px。
#   也就是说：只要口袋比洞口低 3 格以上，人就永远出不来。
#   第二版机器人换了 58 次向、跑了 2700 帧，卡在第二级平台上 —— 不是它笨。
#
# ----- 所以顶层台面必须**在洞口里面** -----
# 顶层台放在 r1（洞口那一行的正下方），宽 3 格、正好等于洞口宽。人站在上面时
# 身体上半截伸进洞口，而洞口那几列是拼装器挖开的，不撞头；往外跳时脚底离
# 父房间地面还有 60px 余量，290px/s 在 0.22 秒里能挪 64px —— 够跨过一格边界。
# **"能出去"是算出来的，不是试出来的。**
#
# ----- 往下靠下穿（Down + Jump） -----
# 四层台间距 3 行，全部盖住洞口那 5 列。这样"往上"是原地跳，"往下"是下穿，
# 两个方向都不需要横向微操。玩家想深入就一路下穿到底层打一场，想走就往上跳。
# ==========================================================================

def pocket():
    g = Grid(18, 10)
    g.carve(1, 1, 16, 8)           # 内腔 16 × 8
    g.solid(1, 9, 16, 9)           # 地板（站面 r8）

    # 洞口 c9，拼装器在父房间地板上挖 3 格（c8..c10）。
    g.put(9, 0, "U")

    # 顶层台**正好等于洞口的三格**。
    #
    # 为什么不能更宽：台面在洞口里，站在台上时身体上半截位于被挖开的那几列中；
    # 台子一旦比洞宽，站在两端的人头就顶进父房间的实心地板（实测会卡住）。
    # 为什么不能再低：台面低一格，往外跳就只剩 12px 余量，人跳得出洞口却挪不上地面。
    g.plat(8, 10, 1)               # 站面 r0，身体伸进洞口
    g.plat(4, 14, 4)               # 站面 r3
    # 最底层台放在 r6 而不是 r7：r7 时它离地板只有 1 行（48px），
    # 平台下面那 9 格地板就废了 —— 这是一个"战斗盒"，底部被劈成两半就不是盒了。
    # r6 让下方留 2 行（96px > 身高 64px），可以从底下走过去。
    g.plat(5, 13, 6)               # 站面 r5

    # 敌人：拼装器会按 tag 重洒，这里只为单看时不是空房。
    g.ground_enemy(3)
    g.ground_enemy(14)
    g.air_enemy(9, 5)

    return g


# ==========================================================================
# 闸门房 44 × 16（紧凑版，替代 100 格宽的 room_01）
#
# 玩法不变：门关着过不去 → 爬三段平台到高台 → 扳拉杆 → 落回地面 → 过门。
# 变的是尺度：原版 room_01 一百格宽，一间房占了整关三分之一，
# 玩家在里面走 20 秒没遇到一个转折点。这一版 44 格，节奏压到 8 秒。
#
# 2026-11-28 第八次：26 行 → 16 行。
# 22 格内腔里只有 r10..r22 这 13 行有东西，上面 9 行是空的 ——
# 玩家看到的是一面 9 行高的黑墙。砍到 12 格内腔后拉杆仍在"要抬头看"的高度，
# 但抬头看到的就是天花板，不是空洞。
#
# 闸门必须**满高**（r1..r12）。留一格缝就等于留了一条"跳过去"的路，
# 生成器的「门关着时到不了出口」判据会当场变红 —— 那条判据是对的。
# ==========================================================================

def gate_room():
    g = Grid(44, 16)
    g.carve(1, 1, 42, 12)          # 内腔 42 × 12
    g.solid(1, 13, 42, 15)         # 地板（站面 r12）

    for y in range(1, 13):
        g.put(30, y, "G")

    # 拉杆在**门左侧**的高台上。放在门右边就是"要开锁才能拿到钥匙"的死锁，
    # 生成器的可达性判据正是这么验的（关着时开关必须够得着）。
    #
    # 行号是"平台行 - 1"：`S` 要站在台面上，而台面那格本身是 `=`。
    # 写在 plat() 之前会被 plat 的断言挡住（c20 r4 已经是 S）。

    # 三段之字，从地板 r12 爬到 r4。每段抬 2~3 行。
    g.plat(1, 9, 10)               # 站面 r9
    g.plat(6, 14, 7)               # 站面 r6
    g.plat(11, 24, 4)              # 站面 r3 ← 拉杆站这儿

    g.put(20, 3, "S")

    g.put(0, 12, "L")
    g.put(43, 12, "R")

    g.ground_enemy(6)
    g.ground_enemy(14)
    g.ground_enemy(36)
    g.air_enemy(26, 6)

    return g


PARTS = {
    "part_pocket": (
        pocket,
        "下沉口袋 · 18×10 · 单 U 口支线",
        "挂在主链地板洞下面。掉进来打一场，再从梯台爬回洞口出去。",
    ),
    "part_gate": (
        gate_room,
        "闸门房 · 44×16 · L/R 横门 · 满高闸门 + 高台拉杆",
        "门关着过不去，爬到高台扳拉杆再落回来。room_01 玩法的紧凑版。",
    ),
    "part_hall": (
        hall,
        "多层厅 · 28×24 · L/R 横门 · 五层之字形平台",
        "横向主链上的挑高房间。进门是 20 格净高的空间，五层平台能一路爬到顶。",
    ),
    "part_tower": (
        tower,
        "高塔 · 18×24 · U/D 竖门 · 五层错落竖井",
        "纯垂直零件。从上门掉进来、从下门掉出去；每层间隔 4 行，反向也爬得回去。",
    ),
    "part_corner": (
        corner,
        "转角房 · 24×20 · L 进 D 出",
        "从左门进来，走到右侧的洞往下掉。用在主链要拐到下一层的位置。",
    ),
    "part_landing": (
        landing,
        "落地厅 · 24×18 · U 进 R 出",
        "从天花板洞掉进来，落地后走到右门。把垂直段接回横向主链。",
    ),
}


def main() -> int:
    show = "--show" in sys.argv
    for name, (fn, title, desc) in PARTS.items():
        g = fn()
        g.check_headroom(name)
        body = g.render()
        head = "\n".join([
            f"! {title}",
            "!",
            f"! {desc}",
            "!",
            "! 这是**零件**，不是房间场景 —— 拼装器只读地形和门位置，",
            "! 场景由 world/level/gen_level.py 拼出来之后统一生成。",
            "!",
            "! 设计脚本：world/tools/build_parts.py（改形状改那个，别手改这张图）",
            "---",
        ])
        text = head + "\n" + body + "\n"
        if show:
            print(text)
        else:
            (OUT / f"{name}.txt").write_text(text, encoding="utf-8", newline="\n")
            print(f"写出 {OUT / (name + '.txt')}  {g.w}×{g.h}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
