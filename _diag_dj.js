const path=require('path');
const { chromium } = require(path.join(process.env.NPM_GLOBAL||'D:/node-dev/npm-global','node_modules/playwright-core'));
const EXE=path.join(process.env.USERPROFILE,'AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe');
const FILE='file:///'+path.resolve(__dirname,'SoulKeep.html').replace(/\\/g,'/');
(async()=>{
  const b=await chromium.launch({executablePath:EXE});
  const p=await (await b.newContext({viewport:{width:1440,height:810}})).newPage();
  await p.goto(FILE,{waitUntil:'load'}); await p.waitForTimeout(1500);
  await p.evaluate(()=>window.__sk.place(336,620));
  await p.waitForTimeout(300);
  const s0 = await p.evaluate(()=>window.__sk.state());
  await p.evaluate(()=>window.__sk.press('jump'));
  await p.waitForTimeout(260);
  const s1 = await p.evaluate(()=>window.__sk.state());
  await p.evaluate(()=>window.__sk.release('jump'));
  await p.waitForTimeout(60);
  const s2 = await p.evaluate(()=>window.__sk.state());
  await p.evaluate(()=>window.__sk.press('jump'));
  await p.waitForTimeout(120);
  const s3 = await p.evaluate(()=>window.__sk.state());
  const f = s=>({y:Math.round(s.y),vy:Math.round(s.vy),jumps:s.jumps,g:s.onGround,st:s.state,buf:s.jumpBuf,am:Math.round(s.airMinY)});
  console.log('起始', JSON.stringify(f(s0)));
  console.log('起跳260ms', JSON.stringify(f(s1)));
  console.log('松开后', JSON.stringify(f(s2)));
  console.log('再按后120ms', JSON.stringify(f(s3)));
  await b.close();
})();
